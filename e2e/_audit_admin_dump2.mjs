import { chromium } from '@playwright/test';
const BASE='http://localhost:3000';
const b=await chromium.launch();
const ctx=await b.newContext({storageState:'e2e/.auth/state.json',viewport:{width:1600,height:1100}});
const p=await ctx.newPage();
await p.goto(`${BASE}/administration?tab=serverMetrics`,{waitUntil:'networkidle'}).catch(()=>{});
await p.waitForTimeout(9000);
console.log('URL:', p.url());
console.log('TITLE:', await p.title());
const html = await p.content();
console.log('htmlLen:', html.length);
const txt = await p.evaluate(()=> document.body ? document.body.innerText : 'NO BODY');
console.log('innerText len:', txt.length);
console.log(txt.slice(0,1800));
await b.close();

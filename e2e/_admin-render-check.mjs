import { chromium } from '@playwright/test';
const BASE='http://localhost:3000';
const b=await chromium.launch();
const ctx=await b.newContext({storageState:'e2e/.auth/state.json',viewport:{width:1600,height:1000}});
const p=await ctx.newPage();
const errs=[],net=[];
p.on('console',m=>{if(m.type()==='error')errs.push(m.text().slice(0,140));});
p.on('response',r=>{const s=r.status();if(s>=400)net.push(s+' '+r.url().replace(BASE,'').split('?')[0]);});
await p.goto(`${BASE}/administration`,{waitUntil:'networkidle',timeout:60000}).catch(e=>console.log('nav:',e.message));
await p.waitForTimeout(5000);
const bodyText=(await p.locator('body').innerText().catch(()=>'')).replace(/\s+/g,' ').trim();
console.log('final url:', p.url());
console.log('body text length:', bodyText.length);
console.log('body head:', bodyText.slice(0,400));
const tabs=await p.getByRole('tab').allInnerTexts().catch(()=>[]);
console.log('tabs:', tabs.length, '->', tabs.join(' | ').slice(0,220));
console.log('4xx/5xx:', net.length); net.slice(0,12).forEach(x=>console.log('  ',x));
console.log('console errors:', errs.length); errs.slice(0,8).forEach(x=>console.log('  ',x));
await p.screenshot({path:'docs/product-readiness-audit/screens/admin-green/_render_check.png',fullPage:false});
await b.close();
